/**
 * Trains the character trigram model of ordinary identifiers and words that `src/charlm.ts` uses to
 * tell a written name from a random string. Identifier parts are taken from the dev corpus and kept
 * only if they recur across many chunks, which keeps hashes and keys (each unique) out of the model.
 *
 *   node scripts/train-charlm.ts > src/charlm-data.ts
 */
import { createReadStream } from "node:fs";
import { join } from "node:path";
import { createInterface } from "node:readline";
import { CORPORA } from "../eval/data-root.ts";

const A = 37; // boundary, a-z, 0-9
const idx = (c: string) => {
	const k = c.charCodeAt(0);
	if (k >= 97 && k <= 122) return k - 96;
	if (k >= 48 && k <= 57) return k - 48 + 27;
	return 0;
};

const partChunks = new Map<string, number>();
const partCount = new Map<string, number>();
const rl = createInterface({ input: createReadStream(join(CORPORA, "built/dev.jsonl")) });
let rows = 0;
for await (const line of rl) {
	if (++rows % 4 !== 0) continue; // a quarter is plenty
	const { text } = JSON.parse(line) as { text: string };
	const seen = new Set<string>();
	for (const m of text.matchAll(/[A-Za-z][A-Za-z0-9]{1,40}/g)) {
		// camelCase, PascalCase, ACRONYMWord, digits split off.
		for (const p of m[0].split(
			/(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])|(?<=[A-Za-z])(?=\d)|(?<=\d)(?=[A-Za-z])/,
		)) {
			const part = p.toLowerCase();
			if (part.length < 2) continue;
			partCount.set(part, (partCount.get(part) ?? 0) + 1);
			if (!seen.has(part)) {
				seen.add(part);
				partChunks.set(part, (partChunks.get(part) ?? 0) + 1);
			}
		}
	}
}

const counts = new Float64Array(A * A * A);
let kept = 0;
for (const [part, chunks] of partChunks) {
	if (chunks < 5) continue;
	kept++;
	// Weight by log frequency so `the` and `self` don't drown everything else.
	const w = 1 + Math.log(partCount.get(part)!);
	const s = `\0\0${part}\0`;
	for (let i = 2; i < s.length; i++) counts[idx(s[i - 2]) * A * A + idx(s[i - 1]) * A + idx(s[i])] += w;
}

// Log-probabilities with add-k smoothing, quantized to bytes: q = round(-log2 p * 16), capped at 255.
const q = new Uint8Array(A * A * A);
for (let ctx = 0; ctx < A * A; ctx++) {
	let total = 0;
	for (let c = 0; c < A; c++) total += counts[ctx * A + c];
	for (let c = 0; c < A; c++) {
		const p = (counts[ctx * A + c] + 0.1) / (total + 0.1 * A);
		q[ctx * A + c] = Math.min(255, Math.round(-Math.log2(p) * 16));
	}
}
console.error(`parts kept: ${kept} of ${partChunks.size}`);
console.log(`// Generated by scripts/train-charlm.ts from public code. Do not edit.
/** Character trigram model of identifier parts: -log2 p(c | two previous) * 16, base64 of ${A}^3 bytes. */
export const CHARLM = "${Buffer.from(q).toString("base64")}";
`);
