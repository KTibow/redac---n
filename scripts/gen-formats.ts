/**
 * Writes src/formats-data.ts from the converted Betterleaks catalog, minus the generic rules this
 * library replaces with its own named-value and random-token layers (they fire dozens of times per MB
 * of ordinary text), minus rules for structure handled in src/structure.ts, and minus rules a core
 * format in src/formats.ts covers better: Azure AD client secrets (the core rule doesn't consume its
 * delimiters, so adjacent secrets are both found), Temporal Cloud keys (JWTs, whose imported regex
 * backtracks quadratically) and Microsoft Teams webhooks (the core rule hides the key, not the tenant's ID). Inline regex modifiers are rewritten away (see withoutModifiers), so every
 * rule compiles on Node 20.
 *
 *   node scripts/gen-formats.ts eval/out/betterleaks-rules.json > src/formats-data.ts
 */
import { readFileSync } from "node:fs";
import { withoutModifiers } from "./regex-modifiers.ts";

const EXCLUDE = new Set([
	"generic-api-key",
	"generic-password",
	"generic-credential-uri",
	"hashicorp-tf-password",
	"kubernetes-secret-yaml",
	"aws-secret-access-key",
	"private-key",
	"jwt",
	"nuget-config-password",
	"gcp-service-account",
	"gcp-application-default-credentials",
	"planetscale-password",
	"sidekiq-secret",
	"twilio-api-key",
	"twilio-account-sid",
	"alibaba-sts-access-key-secret",
	"azure-ad-client-secret",
	"temporal-cloud-api-key",
	"microsoft-teams-webhook",
]);

const TERMINATOR = String.raw`(?:\\?['"\x60]|[\s;]|\\[nr]|$)`;

interface Rule {
	id: string;
	description: string;
	regex: string;
	flags: string;
	keywords: string[];
	kind: string;
	minEntropy: number | null;
}
/**
 * `source` with every capturing group that is repeated made non-capturing: formats.ts takes a rule's first capture as
 * its secret, and a repeated one (`([a-z0-9]{4}-){3}` inside a UUID) holds only its last repetition.
 */
function withoutRepeatedGroups(source: string): string {
	const opens: number[] = [];
	const repeated: number[] = [];
	let inClass = false;
	for (let i = 0; i < source.length; i++) {
		const c = source[i];
		if (c === "\\") i++;
		else if (inClass) inClass = c !== "]";
		else if (c === "[") inClass = true;
		else if (c === "(") opens.push(source[i + 1] === "?" ? -1 : i);
		else if (c === ")") {
			const open = opens.pop()!;
			if (open >= 0 && /[*+?{]/.test(source[i + 1] ?? "")) repeated.push(open);
		}
	}
	let out = source;
	for (const at of repeated.sort((a, b) => b - a)) out = `${out.slice(0, at + 1)}?:${out.slice(at + 1)}`;
	return out;
}

const { rules } = JSON.parse(readFileSync(process.argv[2], "utf8")) as { rules: Rule[] };
const out: [string, string, string, string[], number, number][] = [];
for (const r of rules) {
	if (EXCLUDE.has(r.id) || EXCLUDE.has(r.id.replace(/\.\d+$/, ""))) continue;
	// A human name for the placeholder: "GitHub personal access token" from the description.
	const name = r.id
		.replace(/\.\d+$/, "")
		.replace(/-/g, " ")
		.replace(/\b(api|pat|aws|gcp|jwt|sdk|id|url|oauth)\b/g, (w) => w.toUpperCase());
	// A vendor word must start a word (`box` not in `sandbox`, `linear` not in prose about linear maps).
	let regex = r.kind === "keyword" && /^\(\?(?:i)?:/.test(r.regex) ? `(?<![A-Za-z0-9])${r.regex}` : r.regex;
	// The gitleaks terminator after the token (a quote, a blank, `;`, a `\n` escape or the end) misses
	// keys followed by `,`, `)`, `]`, `&`, `|`, `<`… (arXiv 2609.02983). Any non-word character ends the
	// token instead, unless it joins more of it (`-`, `.`, `+`, `/`, `=` before a word character).
	if (regex.endsWith(TERMINATOR)) regex = `${regex.slice(0, -TERMINATOR.length)}(?![A-Za-z0-9_]|[-.+/=][A-Za-z0-9_])`;
	const [source, flags] = withoutModifiers(withoutRepeatedGroups(regex), r.flags);
	out.push([
		name,
		source,
		flags,
		r.keywords.map((k) => k.toLowerCase()),
		r.minEntropy ?? 0,
		r.kind === "keyword" ? 1 : 0,
	]);
}
console.log(`// Generated by scripts/gen-formats.ts from the Betterleaks rule catalog. Do not edit.
// Betterleaks: https://github.com/betterleaks/betterleaks, MIT License, Copyright (c) 2026 Zachary Rice.
// See THIRD_PARTY_NOTICES.md.

/** [name, regex source, flags, keywords (any must appear, lower case), minimum entropy, 1 if anchored on a vendor word]. */
export const IMPORTED_FORMATS: [string, string, string, string[], number, number][] = ${JSON.stringify(out, null, "\t")
	.replace(/\n\t\t/g, " ")
	.replace(/\n\t\]/g, " ]")};
`);
console.error(`${out.length} formats`);
