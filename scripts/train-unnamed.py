"""
Trains the unnamed-token scorer on scripts/unnamed-data.ts output and reports, with the negatives
split by source (so one repository's quirks can't leak between folds), recall at fixed false-positive
rates (logistic regression as a reference, then LightGBM). With --write, exports the LightGBM trees to
src/model-data.ts, which src/model.ts evaluates.

    python3 -I scripts/train-unnamed.py <train.jsonl> [--write src/model-data.ts]
"""
import json, sys
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold
from sklearn.metrics import roc_auc_score
import lightgbm as lgb

rows = [json.loads(l) for l in open(sys.argv[1])]
X = np.array([r["x"] for r in rows], dtype=float)
y = np.array([r["y"] for r in rows])
# Positives are synthetic; group them randomly, negatives by repository/trajectory source.
rng = np.random.default_rng(0)
groups = np.array([r["src"].split("/")[0] if r["y"] == 0 else f"syn{rng.integers(20)}" for r in rows])

def report(name, scores):
    neg = scores[y == 0]
    pos = scores[y == 1]
    out = [f"{name}: AUC {roc_auc_score(y, scores):.4f}"]
    for fpr in [0.002, 0.005, 0.01, 0.02, 0.05]:
        t = np.quantile(neg, 1 - fpr)
        out.append(f"R@FPR{fpr}={np.mean(pos > t):.3f}(t={t:.3f})")
    print("  ".join(out))

oof_lr = np.zeros(len(y))
oof_gb = np.zeros(len(y))
for tr, te in GroupKFold(n_splits=5).split(X, y, groups):
    lr = LogisticRegression(C=1.0, max_iter=4000, class_weight="balanced")
    lr.fit(X[tr], y[tr])
    oof_lr[te] = lr.predict_proba(X[te])[:, 1]
    gb = lgb.LGBMClassifier(n_estimators=300, num_leaves=15, learning_rate=0.05, min_child_samples=40, subsample=0.8, subsample_freq=1, colsample_bytree=0.8, verbose=-1)
    gb.fit(X[tr], y[tr])
    oof_gb[te] = gb.predict_proba(X[te])[:, 1]
report("logreg", oof_lr)
report("lgbm  ", oof_gb)

if "--write" in sys.argv:
    out = sys.argv[sys.argv.index("--write") + 1]
    gb = lgb.LGBMClassifier(n_estimators=300, num_leaves=15, learning_rate=0.05, min_child_samples=40, subsample=0.8, subsample_freq=1, colsample_bytree=0.8, verbose=-1).fit(X, y)
    dump = gb.booster_.dump_model()
    # Each tree as flat arrays: per node [feature, threshold, left, right]; leaves as negative indices into values.
    trees = []
    for t in dump["tree_info"]:
        feats, thr, left, right, vals = [], [], [], [], []
        def walk(n):
            if "leaf_value" in n:
                vals.append(round(n["leaf_value"], 6))
                return -len(vals)
            i = len(feats)
            feats.append(n["split_feature"]); thr.append(round(n["threshold"], 6)); left.append(0); right.append(0)
            assert n["decision_type"] == "<="
            left[i] = walk(n["left_child"]); right[i] = walk(n["right_child"])
            return i
        walk(t["tree_structure"])
        trees.append([feats, thr, left, right, vals])
    with open(out, "w") as f:
        f.write("// Generated by scripts/train-unnamed.py. Do not edit.\n")
        f.write("/** Boosted trees: per tree [features, thresholds, left, right, leaf values]; a negative child is leaf -(i+1). */\n")
        f.write(f"export const TREES: number[][][] = {json.dumps(trees, separators=(',', ':'))};\n")
        f.write(f"export const FEATURE_COUNT = {X.shape[1]};\n")
    print("wrote", out, len(trees), "trees")

if "--dump" in sys.argv:
    order = np.argsort(-oof_gb)
    print("\n# top-scoring negatives")
    k = 0
    for i in order:
        if y[i] == 0:
            print(f"{oof_gb[i]:.3f} {rows[i]['t'][:50]:50s} | {rows[i]['ctx'][-70:]!r} | {rows[i]['src'][:40]}")
            k += 1
            if k >= 70: break
    print("\n# lowest-scoring positives")
    k = 0
    for i in order[::-1]:
        if y[i] == 1:
            print(f"{oof_gb[i]:.3f} {rows[i]['t'][:50]:50s} | {rows[i]['ctx'][-70:]!r}")
            k += 1
            if k >= 30: break
